// Downloads the latin subsets of the site's Google Fonts into assets/fonts/ and writes
// assets/fonts/fonts.css. Committed so builds and local tests use the exact production fonts
// with no third-party requests. Run by .github/workflows/vendor-fonts.yml (or locally with network).
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const CSS_URL = 'https://fonts.googleapis.com/css2?family=Anton&family=Unbounded:wght@700&family=Inter:wght@400;600&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const dir = path.join(process.cwd(), 'assets/fonts');
await mkdir(dir, { recursive: true });
const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();
const blocks = css.split('/* ').filter((b) => b.startsWith('latin */'));
let out = '/* Self-hosted Google Fonts (latin). Generated by scripts/vendor-fonts.mjs */\n';
for (const b of blocks) {
  const url = b.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const fam = b.match(/font-family: '([^']+)'/)[1];
  const wt = b.match(/font-weight: (\d+)/)[1];
  const name = `${fam.toLowerCase()}-${wt}.woff2`;
  await writeFile(path.join(dir, name), Buffer.from(await (await fetch(url)).arrayBuffer()));
  // Body text uses optional so a late font never re-paints the largest text block.
  out += '/* ' + b.replace(url, `/assets/fonts/${name}`).replace('font-display: swap', fam === 'Inter' ? 'font-display: optional' : 'font-display: swap');
  console.log('saved', name);
}
await writeFile(path.join(dir, 'fonts.css'), out);
